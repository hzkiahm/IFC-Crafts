    private void saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveActionPerformed
        try {
            String orderIDText = orderD.getText().trim();
            String quantityText = quantity.getText().trim();
            String productIDText = productID.getText().trim();
            String priceText = priceatorder.getText().trim();

            Object selected = productname.getSelectedItem();

            if (orderIDText.isEmpty()
                    || selected == null
                    || selected.toString().trim().isEmpty()
                    || quantityText.isEmpty()
                    || productIDText.isEmpty()
                    || priceText.isEmpty()) {

                JOptionPane.showMessageDialog(this, "Please fill in all required fields.");
                return;
            }

            int orderIDValue;
            try {
                String cleanOID = orderIDText.replaceAll("[^0-9]", "");
                orderIDValue = Integer.parseInt(cleanOID);
                if (orderIDValue < 3000) {
                    JOptionPane.showMessageDialog(this, "Order ID must be 3000 or above.");
                    return;
                }
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Order ID must be a valid number.");
                return;
            }

            int productIDValue;
            try {
                String cleanPID = productIDText.replaceAll("[^0-9]", "");
                productIDValue = Integer.parseInt(cleanPID);
                if (productIDValue < 2000 || productIDValue > 2999) {
                    JOptionPane.showMessageDialog(this, "Product ID must be between 2000 and 2999.");
                    return;
                }
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Product ID must be a valid number.");
                return;
            }

            int quantityValue;
            try {
                String cleanQty = quantityText.replaceAll("[^0-9]", "");
                quantityValue = Integer.parseInt(cleanQty);
                if (quantityValue <= 0) {
                    JOptionPane.showMessageDialog(this, "Quantity must be greater than 0.");
                    return;
                }
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Quantity must be a valid number.");
                return;
            }

            double priceValue;
            try {
                String cleanPrice = priceText.replaceAll("[^0-9.]", "");
                priceValue = Double.parseDouble(cleanPrice);
                if (priceValue < 0) {
                    JOptionPane.showMessageDialog(this, "Price at Order cannot be negative.");
                    return;
                }
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Price at Order must be a valid decimal number.");
                return;
            }

            try (Connection conn = getConnection()) {
                String checkOrderSQL = "SELECT * FROM Orders WHERE order_id = ?";
                try (PreparedStatement checkOrder = conn.prepareStatement(checkOrderSQL)) {
                    checkOrder.setInt(1, orderIDValue);
                    try (ResultSet orderRS = checkOrder.executeQuery()) {
                        if (!orderRS.next()) {
                            JOptionPane.showMessageDialog(this, "Order ID does not exist.");
                            return;
                        }
                    }
                }

                String checkProductSQL = "SELECT * FROM Products WHERE product_id = ?";
                try (PreparedStatement checkProduct = conn.prepareStatement(checkProductSQL)) {
                    checkProduct.setInt(1, productIDValue);
                    try (ResultSet productRS = checkProduct.executeQuery()) {
                        if (!productRS.next()) {
                            JOptionPane.showMessageDialog(this, "Product derived does not exist inside Products master table.");
                            return;
                        }
                    }
                }

                String duplicateSQL = "SELECT * FROM Order_Items WHERE order_id = ? AND product_id = ?";
                try (PreparedStatement duplicateStmt = conn.prepareStatement(duplicateSQL)) {
                    duplicateStmt.setInt(1, orderIDValue);
                    duplicateStmt.setInt(2, productIDValue);
                    try (ResultSet duplicateRS = duplicateStmt.executeQuery()) {
                        if (duplicateRS.next()) {
                            JOptionPane.showMessageDialog(this, "This Order Item record already exists.");
                            return;
                        }
                    }
                }

                String summary = "Are you sure you want to save this?\n\n"
                        + "Order ID: " + orderIDValue + "\n"
                        + "Product ID: " + productIDValue + " (" + selected.toString().trim() + ")\n"
                        + "Quantity: " + quantityValue + "\n"
                        + "Price at Order: " + String.format("%.2f", priceValue);

                int confirm = JOptionPane.showConfirmDialog(
                        this, summary, "Confirm Save", JOptionPane.YES_NO_OPTION
                );

                if (confirm != JOptionPane.YES_OPTION) {
                    return;
                }

                String insertSQL = "INSERT INTO Order_Items (order_id, product_id, quantity, price_at_order) VALUES (?, ?, ?, ?)";
                try (PreparedStatement pst = conn.prepareStatement(insertSQL)) {
                    pst.setInt(1, orderIDValue);
                    pst.setInt(2, productIDValue);
                    pst.setInt(3, quantityValue);
                    pst.setDouble(4, priceValue);

                    int rowsInserted = pst.executeUpdate();

                    if (rowsInserted > 0) {
                        JOptionPane.showMessageDialog(this, "Order Item saved successfully!");

                        int choice = JOptionPane.showConfirmDialog(
                                this,
                                "Will you save another record with Order ID " + orderIDValue + "?",
                                "Add Another Item",
                                JOptionPane.YES_NO_OPTION
                        );

                        if (choice == JOptionPane.YES_OPTION) {
                            productname.setSelectedIndex(0);
                            productID.setText("");
                            quantity.setText("");
                            priceatorder.setText("");
                            productname.requestFocus();
                        } else {
                            javax.swing.JFrame frame = (javax.swing.JFrame) javax.swing.SwingUtilities.getWindowAncestor(this);
                            frame.setContentPane(new edittransaction(String.valueOf(orderIDValue)));
                            frame.revalidate();
                            frame.repaint();
                        }
                    } else {
                        JOptionPane.showMessageDialog(this, "Save failed.");
                    }
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Save failed: " + e.getMessage());
            e.printStackTrace();
        }
    }//GEN-LAST:event_saveActionPerformed

