    private void deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteActionPerformed
        try {
            String orderIDText = orderD.getText().trim();
            String productIDText = productID.getText().trim();
            
            if (orderIDText.isEmpty() || productIDText.isEmpty() || productIDText.equals("Not Found") || productIDText.equals("Error")) {
                JOptionPane.showMessageDialog(this, "Valid Order ID and chosen Product Name are required to extract Product ID.");
                return;
            }
            
            if (!quantity.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Only Order ID and Product Name should be valid when deleting.");
                return;
            }

            int orderIDValue;
            try {
                String cleanOID = orderIDText.replaceAll("[^0-9]", "");
                orderIDValue = Integer.parseInt(cleanOID);
                if (orderIDValue < 3000) {
                    JOptionPane.showMessageDialog(this, "Order ID must be 3000 or higher.");
                    return;
                }
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Order ID must be a valid number.");
                return;
            }

            int productIDValue;
            try {
                String cleanPID = productIDText.replaceAll("[^0-9]", "");
                productIDValue = Integer.parseInt(cleanPID);
                if (productIDValue < 2000 || productIDValue > 2999) {
                    JOptionPane.showMessageDialog(this, "Product ID must be from 2000 to 2999.");
                    return;
                }
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Invalid Product ID derived from chosen Product.");
                return;
            }

            try (java.sql.Connection conn = getConnection()) {
                String checkSQL = "SELECT * FROM Order_Items WHERE order_id = ? AND product_id = ?";
                try (java.sql.PreparedStatement checkStmt = conn.prepareStatement(checkSQL)) {
                    checkStmt.setInt(1, orderIDValue);
                    checkStmt.setInt(2, productIDValue);

                    try (java.sql.ResultSet rs = checkStmt.executeQuery()) {
                        if (!rs.next()) {
                            JOptionPane.showMessageDialog(this, "Order Item record does not exist.");
                            return;
                        }

                        int qty = rs.getInt("quantity");
                        double priceAtOrder = rs.getDouble("price_at_order");

                        String message = "Are you sure you want to delete this information?\n\n"
                                + "Order ID: " + orderIDValue + "\n"
                                + "Product ID: " + productIDValue + "\n"
                                + "Quantity: " + qty + "\n"
                                + "Price at Order: " + priceAtOrder;

                        int confirm = JOptionPane.showConfirmDialog(
                                this, message, "Confirm Delete", JOptionPane.YES_NO_OPTION
                        );

                        if (confirm != JOptionPane.YES_OPTION) {
                            return;
                        }
                    }
                }

                String deleteSQL = "DELETE FROM Order_Items WHERE order_id = ? AND product_id = ?";
                try (java.sql.PreparedStatement deleteStmt = conn.prepareStatement(deleteSQL)) {
                    deleteStmt.setInt(1, orderIDValue);
                    deleteStmt.setInt(2, productIDValue);

                    int rowsDeleted = deleteStmt.executeUpdate();
                    if (rowsDeleted > 0) {
                        JOptionPane.showMessageDialog(this, "Order Item deleted successfully!");
                        clearActionPerformed(null);
                    } else {
                        JOptionPane.showMessageDialog(this, "Delete failed.");
                    }
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
            e.printStackTrace();
        }
    }//GEN-LAST:event_deleteActionPerformed

