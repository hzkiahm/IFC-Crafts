    private void fetchProductDetails() {
        Object selected = productname.getSelectedItem();

        if (selected == null || selected.toString().trim().isEmpty()) {
            productID.setText("");
            priceatorder.setText("");
            return;
        }

        String selectedName = selected.toString().trim();

        String query = "SELECT product_id, unit_price FROM Products WHERE product_name = ?";
        try (Connection conn = getConnection();
             PreparedStatement pst = conn.prepareStatement(query)) {
            
            pst.setString(1, selectedName);
            try (ResultSet rs = pst.executeQuery()) {
                if (rs.next()) {
                    int id = rs.getInt("product_id");
                    double price = rs.getDouble("unit_price");
                    
                    productID.setText(String.valueOf(id));
                    priceatorder.setText(String.format("%.2f", price)); 
                } else {
                    productID.setText("Not Found");
                    priceatorder.setText("Not Found");
                }
            }
        } catch (Exception e) {
            productID.setText("Error");
            priceatorder.setText("Error");
        }
    }
    
  
    
    private void loadProductIDs() {
    try (Connection conn = getConnection();
             PreparedStatement pst = conn.prepareStatement("SELECT product_name FROM Products ORDER BY product_name");
             ResultSet rs = pst.executeQuery()) {

            productname.removeAllItems();
            productname.addItem("");

            while (rs.next()) {
                productname.addItem(rs.getString("product_name"));
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                "Failed to load product names: " + e.getMessage()
            );
        }
}
    
    
