    private void deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteActionPerformed
        String idText = inventoryID.getText().trim();

    if (idText.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter Inventory ID first.");
        inventoryID.requestFocus();
        return;
    }

    try {
        int inventoryId = Integer.parseInt(idText);

        try (Connection tempConn = getConnection()) {
            String selectSql =
        "SELECT material, stock_quantity, material_cost "
        + "FROM dbo.Inventory WHERE inventory_id = ?";

            try (PreparedStatement selectPst = tempConn.prepareStatement(selectSql)) {
                selectPst.setInt(1, inventoryId);

                try (ResultSet rs = selectPst.executeQuery()) {
                    if (!rs.next()) {
                        JOptionPane.showMessageDialog(this, "Inventory ID not found.");
                        return;
                    }

                   String message =
                    "Are you sure you want to delete this inventory record?\n\n"
                    + "Inventory ID: " + inventoryId + "\n"
                    + "Material: " + rs.getString("material") + "\n"
                    + "Stock Quantity: " + rs.getInt("stock_quantity") + "\n"
                    + "Material Cost: " + rs.getDouble("material_cost");

                    int confirm = JOptionPane.showConfirmDialog(
                            this,
                            message,
                            "Confirm Delete",
                            JOptionPane.YES_NO_OPTION
                    );

                    if (confirm != JOptionPane.YES_OPTION) {
                        return;
                    }
                }
            }

            String deleteSql = "DELETE FROM dbo.Inventory WHERE inventory_id = ?";

            try (PreparedStatement deletePst = tempConn.prepareStatement(deleteSql)) {
                deletePst.setInt(1, inventoryId);

                int rows = deletePst.executeUpdate();

                if (rows > 0) {
                    JOptionPane.showMessageDialog(this, "Inventory deleted successfully.");
                    clearFields();
                    generateInventoryId();
                } else {
                    JOptionPane.showMessageDialog(this, "Delete failed.");
                }
            }
        }
  

    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Inventory ID must be a number.");
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
    }
    }//GEN-LAST:event_deleteActionPerformed

