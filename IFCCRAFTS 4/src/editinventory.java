    private void saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveActionPerformed
        String materialName = material.getText().trim();
        String stockText = unit.getText().trim();
        String costText = mcost.getText().trim();

        if (materialName.isEmpty() || stockText.isEmpty() || costText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all fields.");
            return;
        }

        try {
            int stockQuantity = Integer.parseInt(stockText);
            double materialCost = Double.parseDouble(costText);

            if (stockQuantity < 0 || materialCost < 0) {
                JOptionPane.showMessageDialog(this, "Stock quantity and material cost cannot be negative.");
                return;
            }

            String message =
                    "Are you sure you want to save this inventory record?\n\n"
                    + "Material: " + materialName + "\n"
                    + "Stock Quantity: " + stockQuantity + "\n"
                    + "Material Cost: " + materialCost;

            int confirm = JOptionPane.showConfirmDialog(
                    this,
                    message,
                    "Confirm Save",
                    JOptionPane.YES_NO_OPTION
            );

            if (confirm != JOptionPane.YES_OPTION) {
                return;
            }

            String sql =
                    "INSERT INTO dbo.Inventory "
                    + "(material, stock_quantity, material_cost) "
                    + "VALUES (?, ?, ?)";

            try (Connection tempConn = getConnection();
                 PreparedStatement pst = tempConn.prepareStatement(sql)) {

                pst.setString(1, materialName);
                pst.setInt(2, stockQuantity);
                pst.setDouble(3, materialCost);

                pst.executeUpdate();
            }

            JOptionPane.showMessageDialog(this, "Inventory saved successfully.");
            clearFields();
            generateInventoryId();

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Stock quantity must be a whole number and material cost must be a number.");
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_saveActionPerformed

